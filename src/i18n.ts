const DICTS: Record<Lang, Dict> = { en, es, pt, zh, ko };

// ---------------------------------------------------------------------------
// Current language: module state plus a hook, so plain functions (notifications,
// background task) and React screens read the same value.
// ---------------------------------------------------------------------------

let current: Lang = "en";
const listeners = new Set<() => void>();

export function isLang(x: unknown): x is Lang {
  return x === "en" || x === "es" || x === "pt" || x === "zh" || x === "ko";
}

export function getLanguage(): Lang {
  return current;
}

export function setLanguage(l: Lang): void {
  if (!isLang(l) || l === current) return;
  current = l;
  for (const fn of listeners) fn();
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Re-renders the calling component when the language changes. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLanguage, getLanguage);
}

/** Device default: Spanish, Portuguese, Chinese or Korean when the phone uses them, else English. */
export function detectLanguage(): Lang {
  let loc = "";
  try {
    loc = Intl.DateTimeFormat().resolvedOptions().locale ?? "";
  } catch {
    loc = "";
  }
  const p = loc.toLowerCase().slice(0, 2);
  return p === "es" || p === "pt" || p === "zh" || p === "ko" ? p : "en";
}

export type Vars = Record<string, string | number>;

export function t(key: Key, vars?: Vars): string {
  const s = DICTS[current][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

type PluralBase = { [K in Key]: K extends `${infer B}.one` ? B : never }[Key];

/** Picks the `.one` or `.other` form and fills {n}. */
export function tn(base: PluralBase, n: number, vars?: Vars): string {
  return t(`${base}.${n === 1 ? "one" : "other"}` as Key, { n, ...vars });
}

/** Looks up a key built at runtime, for example from an id. Falls back to `fallback` when unknown. */
export function tk(key: string, fallback: string, vars?: Vars): string {
  return key in en ? t(key as Key, vars) : fallback;
}

/** The pixel font has Latin and Latin-1 accents only, so Chinese and Korean use the system font. */
export function pixelFontOk(l: Lang = current): boolean {
  return l !== "zh" && l !== "ko";
}

/** Thousands separator for the current language: 3,005 or 3.005. */
export function fmtNum(v: unknown): string {
  const s = String(v ?? "");
  if (!/^\d+$/.test(s)) return s;
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, current === "es" || current === "pt" ? "." : ",");
}

/** Decimal comma for Spanish and Portuguese ("33.5%" -> "33,5%"). Leaves anything else alone. */
export function fmtDec(s: string): string {
  return current === "es" || current === "pt" ? s.replace(/^(\d+)\.(\d+)/, "$1,$2") : s;
}

/** Joins names with the language's list separator. */
export function joinList(items: string[]): string {
  return items.join(t("list.sep"));
}
